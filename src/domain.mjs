export function totals(rows, availableCash) {
  const invested = rows.reduce((sum, h) => sum + h.quantity * h.price, 0);
  const cost = rows.reduce((sum, h) => sum + h.quantity * h.cost, 0);
  return { equity: invested + availableCash, invested, cost, unrealized: invested - cost, returnPct: cost ? (invested - cost) / cost * 100 : 0 };
}
export function allocations(rows, availableCash, group) {
  const buckets = new Map();
  for (const h of rows) {
    const label = group === 'Sector' ? h.sector : group === 'Region' ? 'South Korea' : h.name;
    const existing = buckets.get(label);
    buckets.set(label, { label, value: (existing?.value ?? 0) + h.quantity * h.price, color: existing?.color ?? h.color });
  }
  buckets.set('Cash', { label: 'Cash', value: availableCash, color: '#56657c' });
  const equity = totals(rows, availableCash).equity;
  return [...buckets.values()].map(b => ({ ...b, percent: equity ? b.value / equity * 100 : 0 }));
}
